"""docs/results: before/after tables and charts, generated from the labelled eval runs.

The first labelled run of each kind is the baseline ("before"); every later one shows its delta
against it. Re-run `main.py eval report` after labelling a run; never edit the output by hand.
"""

from pathlib import Path

from rag.domain.models import EvalRun
from rag.evaluation.charts import small_multiples

QUESTION_TYPES = ["comparison_query", "inference_query", "temporal_query", "null_query"]
_HEADER = """# Results

> Generated by `uv run main.py eval report` from the labelled runs in Postgres. Don't edit by hand.
> **Baseline** = the first labelled run of each kind; **Δ** = change against it.
> Label a run with `uv run main.py eval label <run-id> "<label>"`.
"""


def _fmt(v: float | None) -> str:
    return "—" if v is None else f"{v:.2f}"


def _delta(v: float | None, base: float | None) -> str:
    if v is None or base is None:
        return "—"
    d = v - base
    return "0.00" if abs(d) < 0.005 else f"{d:+.2f}".replace("-", "−")


def _commit(run: EvalRun) -> str:
    return f"`{run.provenance.get('git_commit')}{'*' if run.provenance.get('git_dirty') else ''}`"


def _short(qtype: str) -> str:
    return qtype.removesuffix("_query")


def _retrieval_section(runs: list[EvalRun], charts_dir: Path) -> str:
    if not runs:
        return "## Retrieval\n\nNo labelled retrieval runs yet.\n"
    k = runs[0].config["retrieval"]["top_k"]
    metrics = [f"recall@{k}", "fact_recall", "mrr", f"hit@{k}"]
    rows = [r.summary["all"] for r in runs]  # type: ignore[index]
    (charts_dir / "retrieval.svg").write_text(small_multiples(
        "Retrieval: before and after",
        f"Dev split, {rows[0]['questions']} answerable questions · gray = baseline, blue = later experiments",
        [r.label or r.id for r in runs], metrics, [{m: row.get(m) for m in metrics} for row in rows],
    ))
    base = rows[0]
    lines = [
        "## Retrieval",
        "",
        "![Retrieval before and after](charts/retrieval.svg)",
        "",
        f"| Experiment | recall@{k} | Δ | fact recall | Δ | MRR | Δ | hit@{k} | Δ | run | commit |",
        "|---|--:|--:|--:|--:|--:|--:|--:|--:|---|---|",
    ]
    for run, row in zip(runs, rows):
        cells = []
        for m in metrics:
            cells += [_fmt(row.get(m)), "—" if run is runs[0] else _delta(row.get(m), base.get(m))]
        lines.append(f"| {run.label} | " + " | ".join(cells) + f" | `{run.id}` | {_commit(run)} |")
    lines += ["", f"**recall@{k} by question type**", "",
              "| Experiment | " + " | ".join(_short(t) for t in QUESTION_TYPES[:3]) + " |",
              "|---|" + "--:|" * 3]
    for run in runs:
        s = run.summary or {}
        lines.append(f"| {run.label} | " + " | ".join(_fmt(s.get(t, {}).get(f"recall@{k}")) for t in QUESTION_TYPES[:3]) + " |")
    return "\n".join(lines) + "\n"


def _answers_section(runs: list[EvalRun], charts_dir: Path) -> str:
    if not runs:
        return "## Answers\n\nNo labelled answer runs yet.\n"
    panels = ["all", *QUESTION_TYPES]
    (charts_dir / "answers.svg").write_text(small_multiples(
        "Answer accuracy: before and after",
        f"Dev split, {runs[0].summary['all']['questions']}-question sample · gray = baseline, blue = later experiments",  # type: ignore[index]
        [r.label or r.id for r in runs], [_short(p) for p in panels],
        [{_short(p): (r.summary or {}).get(p, {}).get("accuracy") for p in panels} for r in runs],
    ))
    base = runs[0].summary["all"]  # type: ignore[index]
    lines = [
        "## Answers",
        "",
        "![Answer accuracy before and after](charts/answers.svg)",
        "",
        "| Experiment | n | accuracy | Δ | exact match | refusal rate | cited | model · prompt | run | commit |",
        "|---|--:|--:|--:|--:|--:|--:|---|---|---|",
    ]
    for run in runs:
        a = run.summary["all"]  # type: ignore[index]
        lines.append(
            f"| {run.label} | {a['questions']} | {_fmt(a['accuracy'])} | "
            f"{'—' if run is runs[0] else _delta(a['accuracy'], base['accuracy'])} | {_fmt(a['exact_match'])} | "
            f"{_fmt(a['refusal_rate'])} | {_fmt(a['cited'])} | {run.provenance.get('model')} · "
            f"{run.provenance.get('prompt')} | `{run.id}` | {_commit(run)} |"
        )
    return "\n".join(lines) + "\n"


def write_report(results_dir: Path, retrieval_runs: list[EvalRun], answer_runs: list[EvalRun]) -> Path:
    charts_dir = results_dir / "charts"
    charts_dir.mkdir(parents=True, exist_ok=True)
    readme = results_dir / "README.md"
    readme.write_text("\n".join([
        _HEADER,
        _retrieval_section(retrieval_runs, charts_dir),
        _answers_section(answer_runs, charts_dir),
        "`*` after a commit = the run started with uncommitted changes.",
        "",
    ]))
    return readme
